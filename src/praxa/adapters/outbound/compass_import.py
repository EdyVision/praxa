"""Lossless COMPASS allowlist/denylist JSON → Praxa Policy (and back).

COMPASS scenario policies look like:

    {"allowlist": {"topic": "clause text", ...}, "denylist": {...}}

This adapter maps each COMPASS topic to exactly one Rule so category tags
(topic names) remain 1:1 recognizer conditions. Clause text is preserved
verbatim in rule.metadata["clause_text"].
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Literal

from praxa.application.services.policy_builder import PolicyBuilder
from praxa.domain.dispositions import Disposition
from praxa.domain.policy import Condition, Policy

ListType = Literal["allowlist", "denylist"]

_SOURCE_SCHEMA = "compass_allowdeny_v1"
_MAPPER_ID = "compass_import_v1"


def load_compass_policy_json(path: str | Path) -> dict[str, Any]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"COMPASS policy must be a JSON object: {path}")
    return payload


def compass_to_praxa(
    compass: dict[str, Any],
    *,
    policy_id: str,
    domain: str,
    title: str = "",
    description: str = "",
    company: str = "",
    version: str = "0.1.0",
    source_path: str | None = None,
) -> Policy:
    """Map every allowlist/denylist topic to one Praxa rule (lossless text)."""
    builder = (
        PolicyBuilder(policy_id, version=version)
        .domain(domain)
        .title(title or policy_id)
        .description(
            description
            or (
                "Praxa projection of a COMPASS allowlist/denylist policy. "
                "Generated by compass_import_v1; clause text is verbatim."
            )
        )
        .metadata(
            source_schema=_SOURCE_SCHEMA,
            mapper_id=_MAPPER_ID,
            company=company,
            source_path=source_path or "",
        )
    )

    precedence = 0
    for list_type in ("allowlist", "denylist"):
        block = compass.get(list_type) or {}
        if not isinstance(block, dict):
            raise ValueError(f"COMPASS {list_type} must be an object")
        disposition = (
            Disposition.ALLOW if list_type == "allowlist" else Disposition.DENY
        )
        for topic, text in block.items():
            if not isinstance(topic, str) or not topic.strip():
                raise ValueError(f"empty COMPASS topic under {list_type}")
            if not isinstance(text, str):
                raise ValueError(
                    f"COMPASS clause text must be a string: {list_type}.{topic}"
                )
            precedence += 10
            rule_id = f"{list_type}.{topic}"
            builder.rule(
                rule_id,
                title=topic.replace("_", " "),
                disposition=disposition,
                conditions=[Condition(kind="tag", value=topic)],
                required=[topic] if list_type == "allowlist" else [],
                prohibited=[topic] if list_type == "denylist" else [],
                precedence=precedence,
                metadata={
                    "compass_list_type": list_type,
                    "compass_topic": topic,
                    "clause_text": text,
                },
            )

    return builder.build()


def praxa_to_compass(policy: Policy) -> dict[str, dict[str, str]]:
    """Inverse of compass_to_praxa (text + topic keys only)."""
    out: dict[str, dict[str, str]] = {"allowlist": {}, "denylist": {}}
    for rule in policy.rules:
        list_type = rule.metadata.get("compass_list_type")
        topic = rule.metadata.get("compass_topic")
        text = rule.metadata.get("clause_text")
        if list_type not in ("allowlist", "denylist"):
            raise ValueError(f"rule {rule.rule_id}: missing compass_list_type")
        if not isinstance(topic, str) or not topic:
            raise ValueError(f"rule {rule.rule_id}: missing compass_topic")
        if not isinstance(text, str):
            raise ValueError(f"rule {rule.rule_id}: missing clause_text")
        if topic in out[list_type]:
            raise ValueError(
                f"duplicate COMPASS topic after invert: {list_type}.{topic}"
            )
        out[list_type][topic] = text
    return out


def audit_compass_praxa_roundtrip(
    compass: dict[str, Any], policy: Policy
) -> dict[str, Any]:
    """Prove 1:1 topic/text coverage and reconstructible COMPASS JSON."""
    allow = compass.get("allowlist") or {}
    deny = compass.get("denylist") or {}
    if not isinstance(allow, dict) or not isinstance(deny, dict):
        raise ValueError("COMPASS allowlist/denylist must be objects")

    expected_topics = {("allowlist", name) for name in allow} | {
        ("denylist", name) for name in deny
    }

    observed: set[tuple[str, str]] = set()
    text_mismatches: list[str] = []
    for rule in policy.rules:
        list_type = rule.metadata.get("compass_list_type")
        topic = rule.metadata.get("compass_topic")
        text = rule.metadata.get("clause_text")
        if list_type not in ("allowlist", "denylist") or not isinstance(topic, str):
            text_mismatches.append(f"{rule.rule_id}: bad compass metadata")
            continue
        observed.add((list_type, topic))
        original = (allow if list_type == "allowlist" else deny).get(topic)
        if original != text:
            text_mismatches.append(
                f"{list_type}.{topic}: clause_text != COMPASS source"
            )
        expected_disp = (
            Disposition.ALLOW if list_type == "allowlist" else Disposition.DENY
        )
        if rule.disposition != expected_disp:
            text_mismatches.append(
                f"{rule.rule_id}: disposition {rule.disposition} != {expected_disp}"
            )
        tag_values = [c.value for c in rule.conditions if c.kind.lower() == "tag"]
        if topic not in tag_values:
            text_mismatches.append(
                f"{rule.rule_id}: missing tag condition for topic {topic}"
            )

    missing = sorted(expected_topics - observed)
    extra = sorted(observed - expected_topics)
    reconstructed = praxa_to_compass(policy)
    roundtrip_ok = reconstructed == {
        "allowlist": dict(allow),
        "denylist": dict(deny),
    }

    return {
        "ok": not missing and not extra and not text_mismatches and roundtrip_ok,
        "n_compass_topics": len(expected_topics),
        "n_praxa_rules": len(policy.rules),
        "missing_topics": [f"{a}.{b}" for a, b in missing],
        "extra_rules": [f"{a}.{b}" for a, b in extra],
        "text_or_schema_issues": text_mismatches,
        "roundtrip_json_equal": roundtrip_ok,
        "policy_id": policy.policy_id,
        "policy_content_hash": policy.content_hash(),
    }
